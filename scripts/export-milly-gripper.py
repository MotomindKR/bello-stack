#!/usr/bin/env python3
"""Export a standalone MuJoCo gripper with two native loop-closure constraints.

This is a mechanism demonstration using the canonical URDF mass properties,
zero gravity and no contacts. It is not a calibrated Milly dynamics model.

uv run --with numpy --with scipy --with trimesh --with mujoco==3.16.0 \
    scripts/export-milly-gripper.py --check
"""

from __future__ import annotations

import argparse
import math
import os
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation

NS = "https://motomind.kr/bello/urdf"


def numbers(values):
    return " ".join(f"{v:.12g}" for v in values)


def transform(node):
    result = np.eye(4)
    if node is not None:
        result[:3, 3] = np.fromstring(node.get("xyz", "0 0 0"), sep=" ")
        result[:3, :3] = Rotation.from_euler(
            "xyz", np.fromstring(node.get("rpy", "0 0 0"), sep=" ")
        ).as_matrix()
    return result


def pose_attributes(matrix):
    quat = Rotation.from_matrix(matrix[:3, :3]).as_quat()
    return {"pos": numbers(matrix[:3, 3]), "quat": numbers(quat[[3, 0, 1, 2]])}


def resolved(linkage, q):
    r, length, offset, phase, reference = (
        float(linkage.get(name))
        for name in [
            "crank_radius",
            "rod_length",
            "slider_offset",
            "phase",
            "slider_reference",
        ]
    )
    theta = q + phase
    height = offset - r * math.sin(theta)
    horizontal = math.sqrt(length**2 - height**2)
    values = {linkage.get("driver"): q}
    values.update(
        {
            name: r * math.cos(theta) + horizontal - reference
            for name in linkage.get("sliders").split()
        }
    )
    values.update(
        {
            name: math.atan2(height, horizontal) - theta
            for name in linkage.get("rods").split()
        }
    )
    return values


def export(description, output):
    urdf = description / "urdf/milly.urdf"
    source = ET.parse(urdf).getroot()
    linkage = source.find(f"{{{NS}}}slider_crank")
    if linkage is None:
        raise ValueError("Milly URDF is missing the slider-crank parameters")
    links = {link.get("name"): link for link in source.findall("link")}
    joints = {joint.get("name"): joint for joint in source.findall("joint")}
    children = {}
    for joint in joints.values():
        children.setdefault(joint.find("parent").get("link"), []).append(joint)
    home = resolved(linkage, 0.0)
    model = ET.Element("mujoco", model="milly_gripper_loop_closure")
    model.append(
        ET.Comment(
            "Generated by scripts/export-milly-gripper.py. Canonical URDF inertias; no contacts or gravity."
        )
    )
    ET.SubElement(
        model,
        "compiler",
        angle="radian",
        meshdir="../meshes",
        inertiafromgeom="false",
        fusestatic="false",
    )
    ET.SubElement(
        model,
        "option",
        timestep="0.001",
        gravity="0 0 0",
        integrator="implicitfast",
        solver="Newton",
        iterations="100",
        tolerance="1e-12",
    )
    visual = ET.SubElement(model, "visual")
    ET.SubElement(
        visual, "headlight", ambient=".4 .4 .4", diffuse=".8 .8 .8", specular=".2 .2 .2"
    )
    default = ET.SubElement(model, "default")
    ET.SubElement(
        default,
        "geom",
        type="mesh",
        contype="0",
        conaffinity="0",
        group="2",
        density="0",
    )
    ET.SubElement(default, "site", size="0.0015", rgba="1 0.3 0.1 0.7", group="4")
    asset = ET.SubElement(model, "asset")
    ET.SubElement(
        asset,
        "texture",
        type="skybox",
        builtin="gradient",
        rgb1=".94 .95 .96",
        rgb2=".94 .95 .96",
        width="128",
        height="768",
    )
    for material in source.findall("material"):
        ET.SubElement(
            asset,
            "material",
            name=material.get("name"),
            rgba=material.find("color").get("rgba"),
            specular=".3",
            shininess=".4",
        )
    world = ET.SubElement(model, "worldbody")
    ET.SubElement(world, "light", pos=".3 -.3 .5", dir="-.3 .3 -.5", diffuse=".8 .8 .8")
    joint_order = []

    def add_body(name, parent, matrix, joint=None):
        if joint is not None and joint.get("type") != "fixed":
            q = home[joint.get("name")]
            axis = np.fromstring(joint.find("axis").get("xyz"), sep=" ")
            motion = np.eye(4)
            if joint.get("type") == "revolute":
                motion[:3, :3] = Rotation.from_rotvec(axis * q).as_matrix()
            else:
                motion[:3, 3] = axis * q
            matrix = matrix @ motion
        body = ET.SubElement(parent, "body", name=name, **pose_attributes(matrix))
        if joint is not None and joint.get("type") != "fixed":
            joint_name = joint.get("name")
            joint_order.append(joint_name)
            limit = joint.find("limit")
            ET.SubElement(
                body,
                "joint",
                name=joint_name,
                type="hinge" if joint.get("type") == "revolute" else "slide",
                axis=joint.find("axis").get("xyz"),
                ref=str(home[joint_name]),
                range=f"{limit.get('lower')} {limit.get('upper')}",
                damping=".002",
                armature="0.000001",
            )
            source_inertial = links[name].find("inertial")
            if source_inertial is None:
                raise ValueError(f"Missing canonical inertia for {name}")
            inertia = source_inertial.find("inertia")
            a = inertia.attrib
            matrix = np.array(
                [
                    [float(a["ixx"]), float(a["ixy"]), float(a["ixz"])],
                    [float(a["ixy"]), float(a["iyy"]), float(a["iyz"])],
                    [float(a["ixz"]), float(a["iyz"]), float(a["izz"])],
                ]
            )
            frame = transform(source_inertial.find("origin"))
            matrix = frame[:3, :3] @ matrix @ frame[:3, :3].T
            ET.SubElement(
                body,
                "inertial",
                pos=numbers(frame[:3, 3]),
                mass=source_inertial.find("mass").get("value"),
                fullinertia=numbers(
                    [
                        matrix[0, 0],
                        matrix[1, 1],
                        matrix[2, 2],
                        matrix[0, 1],
                        matrix[0, 2],
                        matrix[1, 2],
                    ]
                ),
            )
        for visual in links[name].findall("visual"):
            filename = visual.find("geometry/mesh").get("filename")
            mesh_name = visual.get("name")
            ET.SubElement(
                asset, "mesh", name=mesh_name, file=filename.removeprefix("../meshes/")
            )
            ET.SubElement(
                body,
                "geom",
                name=mesh_name,
                mesh=mesh_name,
                material=visual.find("material").get("name"),
                **pose_attributes(transform(visual.find("origin"))),
            )
        if name.endswith(("_tip", "_pin")):
            ET.SubElement(body, "site", name=name)
        if name == "camera_optical_frame":
            # MuJoCo looks along -Z with +Y up; optical frames use +Z and -Y.
            ET.SubElement(
                body, "camera", name="gripper_camera", euler=f"{math.pi} 0 0", fovy="60"
            )
        for child in children.get(name, []):
            add_body(
                child.find("child").get("link"),
                body,
                transform(child.find("origin")),
                child,
            )
        return body

    mount = np.eye(4)
    mount[:3, :3] = Rotation.from_euler("x", math.pi / 2).as_matrix()
    base = add_body("gripper_base", world, mount)
    camera_relative = np.linalg.inv(
        transform(joints["gripper_base_mount"].find("origin"))
    ) @ transform(joints["camera_mount"].find("origin"))
    add_body("camera_link", base, camera_relative)
    equality = ET.SubElement(model, "equality")
    for side in [1, 2]:
        ET.SubElement(
            equality,
            "connect",
            name=f"finger_{side}_closure",
            site1=f"gripper_rod_{side}_tip",
            site2=f"finger_{side}_pin",
            solref=".002 1",
            solimp=".999 .9999 .001",
        )
    actuators = ET.SubElement(model, "actuator")
    ET.SubElement(
        actuators,
        "position",
        name="gripper_motor",
        joint="gripper",
        kp="2",
        kv=".03",
        ctrlrange="-2.3 0",
        forcerange="-.5 .5",
    )
    keys = ET.SubElement(model, "keyframe")
    for name, q in [("closed", 0.0), ("open", -2.2)]:
        values = resolved(linkage, q)
        ET.SubElement(
            keys,
            "key",
            name=name,
            qpos=numbers([values[joint] for joint in joint_order]),
            ctrl=str(q),
        )
    ET.indent(model, space="  ")
    output.parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(model).write(output, encoding="utf-8", xml_declaration=True)
    with output.open("a") as file:
        file.write("\n")
    return linkage


def check(path, linkage):
    import mujoco

    model = mujoco.MjModel.from_xml_path(str(path))
    data = mujoco.MjData(model)
    assert (model.njnt, model.nu, model.neq) == (5, 1, 2)
    joint_addresses = {
        model.joint(i).name: model.jnt_qposadr[i] for i in range(model.njnt)
    }
    sites = [
        (model.site(f"gripper_rod_{i}_tip").id, model.site(f"finger_{i}_pin").id)
        for i in [1, 2]
    ]

    def error():
        return max(
            np.linalg.norm(data.site_xpos[a] - data.site_xpos[b]) for a, b in sites
        )

    maximum = 0.0
    for q in np.linspace(-2.4, 0.1, 101):
        for name, position in resolved(linkage, q).items():
            data.qpos[joint_addresses[name]] = position
        mujoco.mj_forward(model, data)
        maximum = max(maximum, error())
    assert maximum < 1e-9, maximum
    mujoco.mj_resetData(model, data)
    dynamic_maximum = 0.0
    for i in range(6000):
        data.ctrl[0] = -1.1 * (1 - math.cos(2 * math.pi * i / 6000))
        mujoco.mj_step(model, data)
        dynamic_maximum = max(dynamic_maximum, error())
    assert dynamic_maximum < 1e-4, dynamic_maximum
    assert not any(warning.number for warning in data.warning)
    print(
        f"MuJoCo {mujoco.__version__}: 101 poses + 6000 dynamic steps; maximum loop error "
        f"{maximum * 1000:.6g} mm static / {dynamic_maximum * 1000:.6g} mm dynamic"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--preview",
        action="store_true",
        help="Render the simulated motion as a GIF (requires Pillow and an OpenGL context)",
    )
    args = parser.parse_args()
    description = Path(__file__).resolve().parents[1] / "descriptions/milly"
    output = description / "mjcf/gripper.xml"
    linkage = export(description, output)
    print(output)
    if args.preview and sys.platform.startswith("linux"):
        os.environ.setdefault("MUJOCO_GL", "egl")
    if args.check:
        check(output, linkage)
    if args.preview:
        render_preview(output, description / "previews/gripper-motion.gif")


def render_preview(path, output):
    import mujoco
    from PIL import Image

    model = mujoco.MjModel.from_xml_path(str(path))
    model.vis.global_.offwidth = 900
    model.vis.global_.offheight = 700
    data = mujoco.MjData(model)
    camera = mujoco.MjvCamera()
    mujoco.mjv_defaultFreeCamera(model, camera)
    camera.lookat[:] = [0, -0.025, 0.035]
    camera.distance = 0.32
    camera.azimuth = 130
    camera.elevation = -25
    frames = []
    with mujoco.Renderer(model, 700, 900) as renderer:
        for i in range(6000):
            data.ctrl[0] = -1.1 * (1 - math.cos(2 * math.pi * i / 6000))
            mujoco.mj_step(model, data)
            if i % 150 == 0:
                renderer.update_scene(data, camera=camera)
                frames.append(Image.fromarray(renderer.render()))
    output.parent.mkdir(parents=True, exist_ok=True)
    frames[0].save(
        output, save_all=True, append_images=frames[1:], duration=150, loop=0
    )
    print(output)


if __name__ == "__main__":
    main()
